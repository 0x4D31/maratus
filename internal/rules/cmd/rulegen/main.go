package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type declaration struct {
	identifier string
	ruleID     string
}

func main() {
	dir := flag.String("dir", ".", "rules package directory")
	output := flag.String("output", "catalog_gen.go", "generated catalog path relative to dir")
	flag.Parse()
	if err := run(*dir, *output); err != nil {
		fmt.Fprintln(os.Stderr, "rulegen:", err)
		os.Exit(1)
	}
}

func run(dir, output string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	var declarations []declaration
	seenIdentifiers := map[string]bool{}
	seenRuleIDs := map[string]bool{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == output {
			continue
		}
		file, parseErr := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if parseErr != nil {
			return parseErr
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, raw := range gen.Specs {
				value, ok := raw.(*ast.ValueSpec)
				if !ok || len(value.Names) != 1 || len(value.Values) != 1 {
					continue
				}
				ruleID, isSpec, specErr := specRuleID(value.Values[0])
				if specErr != nil {
					return fmt.Errorf("%s: %w", value.Names[0].Name, specErr)
				}
				if !isSpec {
					continue
				}
				identifier := value.Names[0].Name
				if seenIdentifiers[identifier] {
					return fmt.Errorf("duplicate Spec declaration %s", identifier)
				}
				if seenRuleIDs[ruleID] {
					return fmt.Errorf("duplicate rule ID %q", ruleID)
				}
				seenIdentifiers[identifier] = true
				seenRuleIDs[ruleID] = true
				declarations = append(declarations, declaration{identifier: identifier, ruleID: ruleID})
			}
		}
	}
	sort.Slice(declarations, func(i, j int) bool {
		if declarations[i].ruleID != declarations[j].ruleID {
			return declarations[i].ruleID < declarations[j].ruleID
		}
		return declarations[i].identifier < declarations[j].identifier
	})
	var source bytes.Buffer
	source.WriteString("// Code generated by rulegen; DO NOT EDIT.\n\npackage rules\n\nvar generatedSpecs = []Spec{\n")
	for _, declaration := range declarations {
		fmt.Fprintf(&source, "\t%s,\n", declaration.identifier)
	}
	source.WriteString("}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, output), formatted, 0o644)
}

func specRuleID(expression ast.Expr) (string, bool, error) {
	if call, ok := expression.(*ast.CallExpr); ok {
		identifier, named := call.Fun.(*ast.Ident)
		if !named || identifier.Name != "primitiveRule" {
			return "", false, nil
		}
		if len(call.Args) != 6 {
			return "", true, fmt.Errorf("primitiveRule requires six arguments")
		}
		value, err := stringLiteral(call.Args[0])
		if err != nil || strings.TrimSpace(value) == "" {
			return "", true, fmt.Errorf("primitiveRule requires a nonempty literal rule ID")
		}
		return value, true, nil
	}
	literal, ok := expression.(*ast.CompositeLit)
	if !ok {
		return "", false, nil
	}
	identifier, ok := literal.Type.(*ast.Ident)
	if !ok || identifier.Name != "Spec" {
		return "", false, nil
	}
	var ruleID string
	metadataSeen := false
	seenFields := map[string]bool{}
	for _, element := range literal.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			return "", true, fmt.Errorf("spec must use keyed fields")
		}
		key, ok := field.Key.(*ast.Ident)
		if !ok {
			return "", true, fmt.Errorf("spec contains a non-identifier field")
		}
		if seenFields[key.Name] {
			return "", true, fmt.Errorf("spec declares %s more than once", key.Name)
		}
		seenFields[key.Name] = true
		switch key.Name {
		case "Metadata":
			metadataSeen = true
			var err error
			ruleID, err = metadataRuleID(field.Value)
			if err != nil {
				return "", true, err
			}
		case "Kind", "Match", "MinimumSupport":
		default:
			return "", true, fmt.Errorf("spec contains unsupported field %s", key.Name)
		}
	}
	if !metadataSeen || !seenFields["Kind"] {
		return "", true, fmt.Errorf("spec requires Metadata and Kind fields")
	}
	if !seenFields["Match"] || !seenFields["MinimumSupport"] {
		return "", true, fmt.Errorf("spec requires Match and MinimumSupport")
	}
	return ruleID, true, nil
}

func stringLiteral(expression ast.Expr) (string, error) {
	literal, ok := expression.(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return "", fmt.Errorf("value must be a string literal")
	}
	return strconv.Unquote(literal.Value)
}

func metadataRuleID(expression ast.Expr) (string, error) {
	literal, ok := expression.(*ast.CompositeLit)
	if !ok {
		return "", fmt.Errorf("metadata must be an inline Metadata literal")
	}
	identifier, ok := literal.Type.(*ast.Ident)
	if !ok || identifier.Name != "Metadata" {
		return "", fmt.Errorf("metadata must be an inline Metadata literal")
	}
	for _, element := range literal.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			return "", fmt.Errorf("metadata must use keyed fields")
		}
		key, ok := field.Key.(*ast.Ident)
		if !ok || key.Name != "ID" {
			continue
		}
		value, ok := field.Value.(*ast.BasicLit)
		if !ok || value.Kind != token.STRING {
			return "", fmt.Errorf("metadata.ID must be a string literal")
		}
		id, err := strconv.Unquote(value.Value)
		if err != nil || strings.TrimSpace(id) == "" {
			return "", fmt.Errorf("metadata.ID must be a non-empty string literal")
		}
		return id, nil
	}
	return "", fmt.Errorf("metadata requires an ID field")
}
